package com.gumillea.cosmopolitan;

import com.gumillea.cosmopolitan.core.util.CosmoCompat;
import com.teamabnormals.blueprint.core.annotations.ConfigKey;
import net.minecraftforge.common.ForgeConfigSpec;
import net.minecraftforge.fml.ModList;
import org.apache.commons.lang3.tuple.Pair;

public class CosmoConfig
{
    public static final ForgeConfigSpec COMMON_SPEC;
    public static final CosmoConfig.Common COMMON;

    static {
        final Pair<CosmoConfig.Common, ForgeConfigSpec> specPair = new ForgeConfigSpec.Builder().configure(CosmoConfig.Common::new);
        COMMON_SPEC = specPair.getRight();
        COMMON = specPair.getLeft();
    }

    public static class Common {
        @ConfigKey("enable_apple_flavor")
        public static ForgeConfigSpec.BooleanValue APPLE_FLAVOR;
        @ConfigKey("enable_carrot_flavor")
        public static ForgeConfigSpec.BooleanValue CARROT_FLAVOR;
        @ConfigKey("enable_glow_berry_flavor")
        public static ForgeConfigSpec.BooleanValue GLOW_BERRY_FLAVOR;

        @ConfigKey("enable_enchanted_fruit_flavor")
        public static ForgeConfigSpec.BooleanValue ENCHANTED_FRUIT_FLAVOR;
        @ConfigKey("enable_kabloom_flavor")
        public static ForgeConfigSpec.BooleanValue KABLOOM_FLAVOR;
        @ConfigKey("enable_source_berry_flavor")
        public static ForgeConfigSpec.BooleanValue SOURCE_BERRY_FLAVOR;

        @ConfigKey("bg_tweaks")
        public static ForgeConfigSpec.BooleanValue BERRY_GOOD_COMPAT_TWEAKS;
        @ConfigKey("create_neapolitan_recipe_tweaks")
        public static ForgeConfigSpec.BooleanValue CREATE_NEAPOLITAN_RECIPE_TWEAKS;
        @ConfigKey("tfd_recipe_tweaks")
        public static ForgeConfigSpec.BooleanValue TWILIGHT_DELIGHT_RECIPE_TWEAKS;
        @ConfigKey("seasonals_recipe_tweaks")
        public static ForgeConfigSpec.BooleanValue SEASONALS_RECIPE_TWEAKS;

        public static ForgeConfigSpec.DoubleValue EXUBERANT_MAXIMUM;
        public static ForgeConfigSpec.IntValue GULIME_TICK;
        public static ForgeConfigSpec.DoubleValue GULIME_CHANCE;

        Common(ForgeConfigSpec.Builder builder) {
            builder.push("Items");
            GULIME_TICK = builder.comment("Maximum extra health generated by the Exuberance effect (based on user's max health percentage)")
                    .defineInRange("gulimeTick", 1200, 100, Integer.MAX_VALUE);
            GULIME_CHANCE = builder.comment("Maximum extra health generated by the Exuberance effect (based on user's max health percentage)")
                    .defineInRange("gulimeChance", 0.6, 0.01, 1);
            builder.pop();
            builder.push("Flavors");
            builder.push("Basic Flavors");
            APPLE_FLAVOR = builder.comment("Whether to allow Apple to be crafted into desserts such as ice cream and apply specific mob effects when Neapolitan is installed.")
                    .define("appleFlavor", true);
            CARROT_FLAVOR = builder.comment("Whether to allow Carrot to be crafted into desserts such as ice cream and apply specific mob effects when Neapolitan is installed.")
                    .define("carrotFlavor", true);
            GLOW_BERRY_FLAVOR = builder.comment("Whether to allow Glow Berries to be crafted into desserts such as ice cream and apply specific mob effects when Neapolitan is installed.")
                    .define("glowBerryFlavor", true);
            builder.pop();
            builder.push("Compat Flavors");
            ENCHANTED_FRUIT_FLAVOR = builder.comment("Whether to allow Enchanted Fruit to be crafted into desserts such as ice cream and apply specific mob effects when Neapolitan and Quark are installed.")
                    .define("enchantedFruitFlavor", true);
            KABLOOM_FLAVOR = builder.comment("Whether to allow Kabloom Pulp to be crafted into desserts such as ice cream and apply specific mob effects when Neapolitan and Habitat are installed.")
                    .define("kabloomFlavor", true);
            SOURCE_BERRY_FLAVOR = builder.comment("Whether to allow Source Berry to be crafted into desserts such as ice cream and apply specific mob effects when Neapolitan and Ars Nouveau are installed.")
                    .define("sourceBerryFlavor", true);
            builder.pop();
            builder.pop();
            builder.push("Effects");
            EXUBERANT_MAXIMUM = builder.comment("Maximum extra health generated by the Exuberance effect (based on user's max health percentage)")
                    .defineInRange("exuberantMaximum", 0.3, 0.1, 1.0);
            builder.pop();
            builder.push("Tweaks");
            builder.push("Farming");
            BERRY_GOOD_COMPAT_TWEAKS = builder.comment("Whether to allow tweaks to some of the recipes in Twilight's Flavours & Delights.").define("Twilight's Delights Recipe Tweaks", true);
            builder.pop();
            builder.push("Recipes");
            CREATE_NEAPOLITAN_RECIPE_TWEAKS = builder.comment("Whether to add or adjust Neapolitan's recipes for Create machines.").define("Create & Neapolitan Recipe Tweaks", true);
            TWILIGHT_DELIGHT_RECIPE_TWEAKS = builder.comment("Whether to allow tweaks to some of the recipes in Twilight's Flavours & Delights.").define("Twilight's Delights Recipe Tweaks", true);
            SEASONALS_RECIPE_TWEAKS = builder.comment("Whether to allow tweaks to some of the recipes in Seasonals.").define("Seasonals Recipe Tweaks", true);
            builder.pop();
            builder.pop();
        }
    }
}
